#!/usr/bin/env python3
"""Regenerate the portable source/configuration listing from files on disk."""
from pathlib import Path

root = Path(__file__).resolve().parent.parent
files = [
    *[(str(path.relative_to(root)), "swift") for path in sorted((root / "Source").glob("*.swift"))],
    *[(str(path.relative_to(root)), "swift") for path in sorted((root / "Tests").glob("*.swift"))],
    ("Info.plist", "xml"),
    ("build.sh", "sh"),
    ("install.sh", "sh"),
    ("uninstall.sh", "sh"),
    ("scripts/make-icon.sh", "sh"),
    ("scripts/verify.sh", "sh"),
    ("scripts/package.sh", "sh"),
    ("scripts/render-docs.sh", "sh"),
    ("scripts/test.sh", "sh"),
    ("scripts/render-studio.sh", "sh"),
    (".github/workflows/build.yml", "yaml"),
]
parts = [
    "# PrismDrop source and configuration\n\n"
    "Generated by `python3 scripts/source-listing.py`. Paths are relative to the repository root. "
    "Icon artwork lives in `Assets/`; the optional presentation renderer lives in `tools/`.\n"
]
for name, language in files:
    content = (root / name).read_text().rstrip("\n")
    parts.append(f"\n## `{name}`\n\n```{language}\n{content}\n```\n")
(root / "SOURCE_LISTING.md").write_text("".join(parts))
print("Updated SOURCE_LISTING.md")
